type SpriteProps = { size?: number; className?: string };

function S({
  children,
  size = 48,
  vb = 16,
  className = "",
}: {
  children: React.ReactNode;
  size?: number;
  vb?: number;
  className?: string;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${vb} ${vb}`}
      shapeRendering="crispEdges"
      className={className}
      aria-hidden
    >
      {children}
    </svg>
  );
}

function px(
  x: number,
  y: number,
  w: number,
  h: number,
  fill: string,
  key?: string | number,
) {
  return <rect key={key} x={x} y={y} width={w} height={h} fill={fill} />;
}

